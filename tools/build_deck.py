"""Builds ../deck.js from cards.json (variation definitions) and titles.json (card titles).

For each card: generate the move tree from the opening books (gen.py), validate it,
record book moves that leave the line ("real move, wrong line" hints), and write the deck.

    python3 build_deck.py
"""
import json
import os

import chess

from book import deepest_name, key
from gen import elsewhere, generate

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "deck.js")


def main():
    cards = json.load(open(os.path.join(HERE, "cards.json")))
    titles = json.load(open(os.path.join(HERE, "titles.json")))
    deck, problems = [], 0
    for c in cards:
        side = chess.WHITE if c["s"] == "w" else chess.BLACK
        lines = generate(c)
        graph, ends = {}, set()
        for line in lines:
            b = chess.Board()
            for m in line.split():
                k = key(b)
                mv = b.parse_san(m)                      # raises on an illegal move
                assert b.san(mv) == m, (c["id"], m, b.san(mv))
                b.push(mv)
                graph.setdefault(k, set()).add(key(b))
            if b.turn == side:
                print("line ends on the opponent's move:", c["id"], line)
                problems += 1
            if len(line.split()) < c["p"]:
                print(f"line shorter than the defining ply {c['p']}:", c["id"], line)
                problems += 1
            ends.add(key(b))
        for k, children in graph.items():
            for ck in children:
                if ck not in graph and ck not in ends:
                    print("dead end in", c["id"])
                    problems += 1
        ucis = []
        for line in lines:
            b, u = chess.Board(), []
            for m in line.split():
                mv = b.parse_san(m)
                u.append(mv.uci())
                b.push(mv)
            ucis.append(" ".join(u))
        name, _ = deepest_name(c["pre"][0].split())
        deck.append({"id": c["id"], "t": titles[c["id"]], "e": name[0] if name else "", "s": c["s"], "p": c["p"],
                     "l": ucis, "x": elsewhere(c, lines)})
        print(f"{c['id']:<18} {len(lines):>2} lines, {len(graph):>3} positions")
    body = ",\n".join(json.dumps(d, ensure_ascii=False, separators=(",", ":")) for d in deck)
    with open(OUT, "w") as f:
        f.write("/* Book Moves deck: generated by tools/build_deck.py. Edit tools/cards.json and tools/titles.json instead. */\n")
        f.write("(function (root) {\n\"use strict\";\nconst DECK = [\n" + body + "\n];\n")
        f.write("if (typeof module === \"object\" && module.exports) module.exports = DECK; else root.DECK = DECK;\n")
        f.write("})(typeof self !== \"undefined\" ? self : this);\n")
    print(f"wrote {OUT} ({len(deck)} cards); problems: {problems}")


if __name__ == "__main__":
    main()
